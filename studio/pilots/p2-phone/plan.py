# plan.py — comedy timing for "My phone at 1%": each beat lasts as long as its line plus the pause the joke needs.
# Writes build/edit.js (shots, voice placements, captions, lip-sync) and edit.json (for audio.py).
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.join(HERE, '..', '..', 'lib'))
from captions import time_words, pages, norm
lines = {l['id']: l for l in json.load(open(os.path.join(HERE, 'lines.json')))}
durs = {l['id']: l['dur'] for l in json.load(open(os.path.join(HERE, 'vo', 'lines.json')))}
words = {k: json.load(open(os.path.join(HERE, 'vo', k + '.words.json'))) for k in lines}
FPS = 30
# beat: (shot name, line id or None, lead-in, tail)
BEATS = [('S1_phone', 'p1', 0.45, 0.15), ('S2_tears', 'p2', 0.1, 0.4), ('S3_charger', 'c1', 0.15, 0.2), ('S4_gap', 'p3', 0.45, 0.3),
         ('S5_charger', 'c2', 0.1, 0.15), ('S6_rage', 'p4', 0.05, 0.35), ('S7_lift', 'p5', 0.55, 0.15), ('S8_video', 'p6', 0.3, 1.0),
         ('S9_rip', 'c3', 0.6, 0.55), ('S10_end', None, 0.0, 2.2)]
shots, voice, t = [], [], 0.0
for name, lid, lead, tail in BEATS:
    dur = lead + (durs[lid] if lid else 0) + tail; dur = round(round(dur * FPS) / FPS, 4)
    shots.append({'name': name, 't0': round(t, 4), 't1': round(t + dur, 4)})
    if lid: voice.append({'id': lid, 'at': round(t + lead, 4), 'who': lines[lid]['who'], 'dur': durs[lid]})
    t += dur
AT = {v['id']: v['at'] for v in voice}
def wt(lid, w, end=False, k=0):
    tw = time_words(lines[lid]['text'], words[lid]); hits = [(s, e) for x, (s, e) in tw if norm(x) == norm(w)]
    s, e = hits[min(k, len(hits) - 1)]; return round(AT[lid] + (e if end else s), 4)
S = {s['name']: s for s in shots}
EV = {'gray': wt('p4', 'Gray'), 'calc': wt('p4', 'calculator'), 'calcEnd': S['S6_rage']['t1'] - 0.05,
      'grab': S['S7_lift']['t0'] + 0.1, 'lift': S['S7_lift']['t0'] + 0.5, 'video': S['S8_video']['t0'] + 0.15,
      'die': S['S8_video']['t1'] - 0.55, 'moon': wt('p3', 'moon'), 'six': wt('p3', 'Six')}
caps = []
for v in voice:
    l = lines[v['id']]; tw = time_words(l['text'], words[v['id']]); emph = set(norm(x) for x in l.get('emph', []))
    for pg in pages(tw, 3):
        caps.append({'who': l['who'], 't0': round(v['at'] + pg[0][1], 3), 't1': round(v['at'] + pg[-1][2], 3),
                     'words': [{'w': w, 's': round(v['at'] + s, 3), 'e': round(v['at'] + e, 3), 'em': norm(w) in emph} for w, s, e in pg]})
for i, p in enumerate(caps):
    nxt = caps[i + 1]['t0'] if i + 1 < len(caps) else p['t1'] + 0.5
    p['t1'] = round(min(nxt - 0.02, p['t1'] + 0.55), 3) if nxt > p['t1'] else round(p['t1'], 3)
edit = {'FPS': FPS, 'SHOTS': shots, 'DURATION': round(t, 4), 'EV': EV, 'VOICE': voice, 'CUTS': [s['t0'] for s in shots[1:]]}
json.dump(edit, open(os.path.join(HERE, 'edit.json'), 'w'), indent=1)
mouth = json.load(open(os.path.join(HERE, 'build', 'mouth.json')))
open(os.path.join(HERE, 'build', 'edit.js'), 'w').write('// generated by plan.py\nexport const EDIT = ' + json.dumps(edit) + ';\nexport const CAPTIONS = ' + json.dumps(caps) +
    ';\nexport const MOUTH = ' + json.dumps(mouth) + ';\n')
print('duration', edit['DURATION']); [print(f"  {s['name']:<11} {s['t0']:6.2f} – {s['t1']:6.2f}") for s in shots]; print(EV)
