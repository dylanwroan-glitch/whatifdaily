# plan.py — narration-driven edit for the narrated Eiffel cut: every shot lasts as long as its voice line (plus a short
# lead-in and a tail for the action), number counters land on the spoken number, and the captions follow the voice.
# Writes build/edit.js (for the page), edit.json (for audio.py) and build/captions.json.
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.join(HERE, '..', '..', 'lib'))
from captions import time_words, pages, norm

lines = json.load(open(os.path.join(HERE, 'lines.json')))
durs = {l['id']: l['dur'] for l in json.load(open(os.path.join(HERE, 'vo', 'lines.json')))}
words = {l['id']: json.load(open(os.path.join(HERE, 'vo', l['id'] + '.words.json'))) for l in lines}
FPS = 30
LEAD = {'H_hook': 0.2, 'D_reveal': 0.02, 'C_size': 0.05}
TAIL = {'H_hook': 0.3, 'A_rivets': 0.25, 'B_heat': 0.45, 'B_top': 0.4, 'B_mid': 0.45, 'B_legs': 0.65, 'C_size': 0.35, 'C_foot': 0.3,
        'D_spread': 0.55, 'D_tease': 1.05, 'D_reveal': 0.35, 'D_wide': 0.2, 'E_why': 0.15, 'E_holes': 0.3, 'F_end': 1.3}
shots, voice, t = [], [], 0.0
for l in lines:
    lead = LEAD.get(l['shot'], 0.1); dur = lead + durs[l['id']] + TAIL.get(l['shot'], 0.12)
    dur = round(round(dur * FPS) / FPS, 4)  # whole frames, so the cut list and the score agree exactly
    shots.append({'name': l['shot'], 't0': round(t, 4), 't1': round(t + dur, 4), 'set': 'P'})
    voice.append({'id': l['id'], 'at': round(t + lead, 4)}); t += dur
S = {s['name']: s for s in shots}; AT = {v['id']: v['at'] for v in voice}
def wend(lid, w, k=0):  # end time of the k-th occurrence of word w in line lid (absolute)
    tw = time_words(next(l['text'] for l in lines if l['id'] == lid), words[lid]); hits = [e for x, (s, e) in tw if norm(x) == norm(w)]
    return round(AT[lid] + hits[min(k, len(hits) - 1)], 4)
def frac(n, f): s = S[n]; return round(s['t0'] + (s['t1'] - s['t0']) * f, 4)
EV = {
  'hookHit': 0.0,
  'tall': [frac('A_tall', 0.05), wend('a1', 'thirty')], 'iron': [frac('A_iron', 0.05), wend('a2', 'hundred')],
  'rivets': [frac('A_rivets', 0.03), wend('a3', 'million')], 'temp': [frac('B_heat', 0.05), wend('b1', 'hundred')],
  'cube': [frac('C_size', 0.03), wend('c2', 'eight')], 'deep': [S['D_reveal']['t0'], wend('d3', 'Six')],
  'melt0': S['B_top']['t0'], 'melt1': S['B_legs']['t1'],
  'gather0': frac('C_cube', 0.03), 'gather1': frac('C_cube', 0.86), 'slide0': frac('C_foot', 0.2), 'slide1': frac('C_foot', 0.62),
  'spread0': frac('D_spread', 0.08), 'spread1': frac('D_spread', 0.86), 'reveal': S['D_reveal']['t0'], 'tease': S['D_tease']['t0'],
  'rebuild0': frac('F_end', 0.03), 'rebuild1': frac('F_end', 0.66),
}
caps = []
for l in lines:
    if l['id'] == 'f1': continue  # the end card shows this line
    tw = time_words(l['text'], words[l['id']]); emph = set(norm(x) for x in l.get('emph', []))
    for pg in pages(tw, 3):
        caps.append({'line': l['id'], 'src': l.get('src', ''), 't0': round(AT[l['id']] + pg[0][1], 3), 't1': round(AT[l['id']] + pg[-1][2], 3),
                     'words': [{'w': w, 's': round(AT[l['id']] + s, 3), 'e': round(AT[l['id']] + e, 3), 'em': norm(w) in emph} for w, s, e in pg]})
for i, p in enumerate(caps):  # hold each page until the next starts (max 0.6 s), then clear
    nxt = caps[i + 1]['t0'] if i + 1 < len(caps) else p['t1'] + 0.5
    p['t1'] = round(min(nxt - 0.02, p['t1'] + 0.6), 3) if nxt > p['t1'] else round(p['t1'], 3)
edit = {'FPS': FPS, 'SHOTS': shots, 'DURATION': round(t, 4), 'EV': EV, 'VOICE': voice, 'CUTS': [s['t0'] for s in shots[1:]]}
json.dump(edit, open(os.path.join(HERE, 'edit.json'), 'w'), indent=1)
json.dump(caps, open(os.path.join(HERE, 'build', 'captions.json'), 'w'), indent=1)
open(os.path.join(HERE, 'build', 'edit.js'), 'w').write('// generated by plan.py\nexport const EDIT = ' + json.dumps(edit) + ';\nexport const CAPTIONS = ' + json.dumps(caps) + ';\n')
print('duration', edit['DURATION'], 'shots', len(shots), 'caption pages', len(caps))
for s in shots: print(f"  {s['name']:<9} {s['t0']:6.2f} – {s['t1']:6.2f}  ({s['t1'] - s['t0']:.2f} s)")
